def crc16(bs):
    c=0xFFFF
    for b in bs:
        c^=b
        for _ in range(8):
            c=(c>>1)^0xA001 if c&1 else c>>1
    return c
def frame(bs):
    c=crc16(bs);return bs+[c&0xFF,c>>8]
