def wave(bits,x0,yh,yl,w=34):
    d=f'M{x0} {yh if bits[0] else yl}';x=x0;cur=bits[0]
    for b in bits:
        if b!=cur:d+=f' L{x} {yh if b else yl}';cur=b
        x+=w;d+=f' L{x} {yh if b else yl}'
    return d
