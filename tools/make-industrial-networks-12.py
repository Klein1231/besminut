def _clean(t):
    t=re.sub(r'<svg.*?</svg>|<table>.*?</table>','',t,flags=re.S)
    t=re.sub(r'<b>([^<]*?)\.</b>',r'<b>\1</b>',t)
    t=re.sub(r'\b(рус|ағылш|нем|мс)\.','\\1',t)
    return t
