def t_ms(n,baud=9600,slave=20):
    ch=11/baud*1000                     # 8E1: 11 bits per character
    return (8+5+2*n)*ch+2*3.5*ch+slave  # request 8 B, response 5+2n B, two 3.5-char silences, slave delay
